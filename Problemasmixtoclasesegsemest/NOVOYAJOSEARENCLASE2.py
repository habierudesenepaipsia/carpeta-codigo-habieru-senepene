#la programacion orientada a objetos es un paradigma
#los paradigmas ocurren en toda la vida, se hace algo porque siempre se ha hecho asi y se va a seguir haciendo asi
#lo complicado es romper el paradigma, porque para romperlo hay que saber como se hizo porque se hizo etc.
#el paradigma orientado a objetos nos indica que todo en esta vida es atribuido a objetos
#todo objeto tiene atributos y metodos, nosotros como seres humanos somos los mismos en atributos y metodos, pero con diferencias
#los atributos son todas las cosas que diferencian a los objetos, por ej altura
#los metodos son las acciones que tienen los objetos, los verbos diferentes que tienen, como los kilometros de un auto  
